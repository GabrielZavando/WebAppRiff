/**
 * Generates gitignored environment files from build-time environment
 * variables (task 1.1 + dev-credentials flow, design D3).
 *
 * Targets:
 * - (default / `--target=prod`) → `src/environments/environment.production.ts`
 *   Consumed by the production build via fileReplacements. Used by CI/CD.
 * - `--target=dev` → `src/environments/environment.development.local.ts`
 *   Replaces the committed `environment.development.ts` (placeholders) in the
 *   development build so devs can use real credentials without touching git.
 *
 * Flags:
 * - `--if-missing` → write only when the target file does not exist yet
 *   (used by npm pre/post hooks so a dev's real local values are never
 *   clobbered by an automated run).
 * - `WRITE_ENV_ROOT` (env var) → overrides the app root directory (used by
 *   the unit tests to run the script against a temp copy).
 *
 * Missing variables produce a warning and an empty value, EXCEPT for the
 * `--if-missing` bootstrap (dev target), which falls back to the same
 * placeholder values as the committed `environment.development.ts` — an empty
 * `apiKey` would make `getAuth()` throw `auth/invalid-api-key` and crash the
 * app at bootstrap (verified; see verification.md).
 *
 * Env vars: FIREBASE_API_KEY, FIREBASE_AUTH_DOMAIN, FIREBASE_PROJECT_ID,
 * FIREBASE_APP_ID, API_BASE_URL (fallback `http://localhost:3000/api/v1`,
 * the backend's `resolvePort` default).
 */
import { existsSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const appRoot = process.env['WRITE_ENV_ROOT'] ?? resolve(scriptDir, '..');

const args = process.argv.slice(2);
const targetArg = args.find((arg) => arg.startsWith('--target='));
const target = targetArg === undefined ? 'prod' : targetArg.split('=')[1];
const ifMissing = args.includes('--if-missing');

if (target !== 'dev' && target !== 'prod') {
  console.error(`[write-env] Invalid --target '${target}'. Use dev or prod.`);
  process.exit(1);
}

const has = (name) =>
  process.env[name] !== undefined && process.env[name] !== '';

const values = {
  FIREBASE_API_KEY: has('FIREBASE_API_KEY') ? process.env['FIREBASE_API_KEY'] : '',
  FIREBASE_AUTH_DOMAIN: has('FIREBASE_AUTH_DOMAIN')
    ? process.env['FIREBASE_AUTH_DOMAIN']
    : '',
  FIREBASE_PROJECT_ID: has('FIREBASE_PROJECT_ID')
    ? process.env['FIREBASE_PROJECT_ID']
    : '',
  FIREBASE_APP_ID: has('FIREBASE_APP_ID') ? process.env['FIREBASE_APP_ID'] : '',
  API_BASE_URL: has('API_BASE_URL')
    ? process.env['API_BASE_URL']
    : 'http://localhost:3000/api/v1',
};

/** Committed dev placeholder defaults (safe: boot never crashes with them). */
const DEV_PLACEHOLDERS = {
  FIREBASE_API_KEY: 'dev-placeholder-api-key',
  FIREBASE_AUTH_DOMAIN: 'dev-placeholder.firebaseapp.com',
  FIREBASE_PROJECT_ID: 'dev-placeholder',
  FIREBASE_APP_ID: 'dev-placeholder-app',
  API_BASE_URL: 'http://localhost:3000/api/v1',
};

const fileName =
  target === 'dev'
    ? 'environment.development.local.ts'
    : 'environment.production.ts';
const targetPath = resolve(appRoot, 'src/environments', fileName);

if (ifMissing && existsSync(targetPath)) {
  console.log(`[write-env] ${fileName} already exists; nothing to do.`);
} else {
  const bootstrap = target === 'dev' && ifMissing;
  const effective = bootstrap ? { ...values, ...DEV_PLACEHOLDERS } : values;

  for (const [name, value] of Object.entries(effective)) {
    if (value === '') {
      console.warn(`[write-env] WARNING: ${name} is not set; writing empty value.`);
    }
  }

  const output = `/**
 * GENERATED FILE — do not edit or commit (task 1.1 / design D3).
 * Generated by scripts/write-env.mjs from build-time environment variables.
 */
import type { AdminEnvironment } from './environment.model';

export const environment: AdminEnvironment = {
  firebase: {
    apiKey: '${effective.FIREBASE_API_KEY}',
    authDomain: '${effective.FIREBASE_AUTH_DOMAIN}',
    projectId: '${effective.FIREBASE_PROJECT_ID}',
    appId: '${effective.FIREBASE_APP_ID}',
  },
  apiBaseUrl: '${effective.API_BASE_URL}',
};
`;

  writeFileSync(targetPath, output, 'utf-8');
  console.log(`[write-env] wrote ${targetPath}`);
}
